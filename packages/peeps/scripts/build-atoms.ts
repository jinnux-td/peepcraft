// Converts the Open Peeps "Separate Atoms" SVGs into React components: src/atoms/<category>/<Name>.ts plus an index per category.
// Usage: node scripts/build-atoms.ts "<path to>/Flat Assets/Separate Atoms"
// No dependencies: the atoms hold only <g>, <path> and (once) a mask, so a small tag reader is enough. Path data is copied verbatim.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const sources: Array<{ dir: string; category: string }> = [
  { dir: 'accessories', category: 'accessories' },
  { dir: 'body', category: 'body' },
  { dir: 'face', category: 'face' },
  { dir: 'facial-hair', category: 'facialHair' },
  { dir: 'head', category: 'head' },
  { dir: 'pose/standing', category: 'standing' },
  { dir: 'pose/sitting', category: 'sitting' },
]
const INK = new Set(['#000000', '#231f20', '#221e1f']) // the pack's blacks (two files use off-black)
const PAPER = new Set(['#ffffff', 'white'])
const SKIP_TAGS = new Set(['title', 'desc'])
const SKIP_ATTRS = new Set(['id', 'version', 'xmlns', 'xmlns:xlink', 'width', 'height', 'viewBox'])

interface Node { tag: string; attrs: Record<string, string>; kids: Node[] }

function parse(svg: string): Node {
  const root: Node = { tag: '#root', attrs: {}, kids: [] }
  const stack = [root]
  for (const m of svg.matchAll(/<(\/?)([a-zA-Z][\w:-]*)([^>]*?)(\/?)>/g)) {
    const [, close, tag, rawAttrs, selfClose] = m
    if (close) { stack.pop(); continue }
    const attrs: Record<string, string> = {}
    for (const a of rawAttrs.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[a[1]] = a[2]
    const node: Node = { tag, attrs, kids: [] }
    stack[stack.length - 1].kids.push(node)
    if (!selfClose) stack.push(node)
  }
  return root.kids[0]
}

const camel = (s: string) => s.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())
const pascal = (s: string) => s.replace(/[^A-Za-z0-9]+/g, ' ').trim().split(' ').map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const kebab = (s: string) => s.replace(/[^A-Za-z0-9]+/g, ' ').trim().toLowerCase().replace(/ /g, '-')
const str = (s: string) => JSON.stringify(s)

function referenced(n: Node, into = new Set<string>()): Set<string> {
  for (const v of Object.values(n.attrs)) for (const m of v.matchAll(/#([\w-]+)/g)) into.add(m[1])
  n.kids.forEach((k) => referenced(k, into))
  return into
}

function attrCode(name: string, value: string, inMask: boolean, refs: Set<string>): string | null {
  if (name === 'id') return refs.has(value) ? `id: c.ref(${str(value)})` : null
  if (SKIP_ATTRS.has(name)) return null
  const key = name === 'xlink:href' ? 'href' : camel(name)
  if ((name === 'fill' || name === 'stroke') && !inMask) {
    const v = value.toLowerCase()
    if (INK.has(v)) return `${key}: c.ink`
    if (PAPER.has(v)) return `${key}: c.paper`
  }
  const withRefs = /#[\w-]+/.test(value) && refs.size
  if (withRefs) return `${key}: ${'`' + value.replace(/#([\w-]+)/g, (_, r: string) => '#${c.ref(' + str(r) + ')}') + '`'}`
  return `${key}: ${str(value)}`
}

function code(n: Node, refs: Set<string>, depth: number, inMask = false): string {
  const pad = '  '.repeat(depth)
  const attrs = Object.entries(n.attrs).map(([k, v]) => attrCode(k, v, inMask, refs)).filter((a): a is string => a !== null)
  const kids = n.kids.filter((k) => !SKIP_TAGS.has(k.tag)).map((k) => code(k, refs, depth + 1, inMask || n.tag === 'mask'))
  const props = attrs.length ? `{ ${attrs.join(', ')} }` : 'null'
  if (!kids.length) return `${pad}h(${str(n.tag)}, ${props})`
  return `${pad}h(${str(n.tag)}, ${props},\n${kids.join(',\n')},\n${pad})`
}

function convert(file: string, category: string, name: string) {
  const root = parse(readFileSync(file, 'utf8'))
  const [, , w, h] = (root.attrs.viewBox ?? '').split(/\s+/).map(Number)
  if (!(w > 0 && h > 0)) throw new Error(`${file}: no viewBox`)
  const id = kebab(name.replace(/^\*\s*/, ''))
  const refs = referenced(root)
  const body = root.kids.filter((k) => !SKIP_TAGS.has(k.tag)).map((k) => code(k, refs, 1))
  const ident = pascal(name.replace(/^\*\s*/, ''))
  const src = `// Generated by scripts/build-atoms.ts from ${category}/${name}.svg. Do not edit.
import { createElement as h } from 'react'
import { atom } from '../../atom.ts'

export const ${ident} = atom({ category: ${str(category)}, id: ${str(id)}, label: ${str(name)}, width: ${w}, height: ${h} }, (c) => [
${body.join(',\n')},
])
`
  return { id, ident, src }
}

const root = process.argv[2]
if (!root) throw new Error('usage: node scripts/build-atoms.ts "<Flat Assets>/Separate Atoms"')
const out = new URL('../src/atoms/', import.meta.url).pathname
rmSync(out, { recursive: true, force: true })
let total = 0
for (const { dir, category } of sources) {
  const folder = join(root, dir)
  mkdirSync(join(out, category), { recursive: true })
  const seen = new Map<string, string>()
  const exports: string[] = []
  for (const f of readdirSync(folder).filter((f) => f.endsWith('.svg')).sort()) {
    const name = f.replace(/\.svg$/, '')
    const { id, ident, src } = convert(join(folder, f), category, name)
    if (seen.has(id) || seen.has(ident)) throw new Error(`${category}: "${name}" collides with "${seen.get(id) ?? seen.get(ident)}"`)
    seen.set(id, name); seen.set(ident, name)
    writeFileSync(join(out, category, `${ident}.ts`), src)
    exports.push(ident)
    total++
  }
  const list = exports.map((e) => `  ${e},`).join('\n')
  writeFileSync(join(out, category, 'index.ts'), `// Generated by scripts/build-atoms.ts. Do not edit.
${exports.map((e) => `import { ${e} } from './${e}.ts'`).join('\n')}

export const atoms = [
${list}
] as const
export type Id = (typeof atoms)[number]['id']
`)
  console.log(category.padEnd(12), exports.length)
}
console.log('atoms', total)
