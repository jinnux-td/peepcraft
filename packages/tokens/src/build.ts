// Generates the CSS and JSON outputs from src/tokens.ts. Pure functions; src/write.ts puts them on disk.
// Every selector is wrapped in :where() (specificity 0), so a host or a component can override any token with a plain rule,
// and between these blocks the later one wins: brand over mode, an explicit data-theme over the system mode.
import { BRANDS, BREAKPOINTS, COLOR_ROLES, MODES, SCALES, brandSets, type Colors, type ScaleName } from './tokens.ts';

const HEAD = (what: string) => `/* ${what}\n   Generated by @kit/tokens from src/tokens.ts: do not edit, run \`npm run build\`. */\n`;
const decls = (pairs: [string, string][]) => pairs.map(([k, v]) => `  ${k}: ${v};`).join('\n');
const block = (sel: string, body: string) => `${sel} {\n${body}\n}\n`;
const colorDecls = (c: Colors, scheme: string) => decls([['color-scheme', scheme], ...COLOR_ROLES.map((r) => [`--k-${r}`, c[r]] as [string, string])]);

// tokens.css: the scales once, light (also the default), dark when the system asks and no data-theme says otherwise,
// dark when data-theme says so, then each brand as a complete colour set plus its scale overrides.
// A brand with both modes writes each colour as light-dark(light, dark): it sets no color-scheme of its own, so the colour resolves
// where it is used, by the mode that element inherits. It is declared again on every data-theme inside it, after the mode blocks,
// or a nested mode would reset the colours to the kit's.
export function tokensCss(): string {
  const scales = decls(Object.entries(SCALES).map(([k, v]) => [`--k-${k}`, v]));
  const dark = colorDecls(MODES.dark, 'dark');
  const brands = Object.entries(BRANDS).map(([name, b]) => {
    const own = Object.entries(b.scales ?? {}).map(([k, v]) => [`--k-${k}`, v as string] as [string, string]);
    const sets = brandSets(b), [[mode, first]] = sets;
    const colors = sets.length === 1 ? colorDecls(first, mode)
      : decls(COLOR_ROLES.map((r) => [`--k-${r}`, `light-dark(${sets[0][1][r]}, ${sets[1][1][r]})`] as [string, string]));
    const sel = sets.length === 1 ? `:where([data-brand=${name}])` : `:where([data-brand=${name}], [data-brand=${name}] [data-theme])`;
    return block(sel, `${colors}${own.length ? '\n' + decls(own) : ''}`);
  });
  return HEAD('Kit design tokens: --k-* for light, dark and each brand theme (data-theme, data-brand).')
    + block(':where(:root)', scales)
    + block(':where(:root, [data-theme=light])', colorDecls(MODES.light, 'light'))
    + `@media (prefers-color-scheme: dark) {\n${block(':where(:root:not([data-theme=light]))', dark).replace(/^/gm, '  ').trimEnd()}\n}\n`
    + block(':where([data-theme=dark])', dark)
    + brands.join('');
}

// tailwind.css: a Tailwind v4 theme on the tokens. `inline` makes each utility read the variable where it is used, so it
// follows data-theme and data-brand on any ancestor. Breakpoints replace Tailwind's own (tablet, desktop, wide).
export function tailwindCss(): string {
  const v = (n: string) => `var(--k-${n})`;
  const pick = (prefix: string) => (Object.keys(SCALES) as ScaleName[]).filter((k) => k.startsWith(prefix));
  const theme: [string, string][] = [
    ...COLOR_ROLES.filter((r) => r !== 'page-fill').map((r) => [`--color-${r}`, v(r)] as [string, string]),
    ...pick('font-').map((k) => [`--${k}`, v(k)] as [string, string]),
    ...pick('text-').map((k) => [`--${k}`, v(k)] as [string, string]),
    ...pick('leading-').map((k) => [`--${k}`, v(k)] as [string, string]),
    ['--spacing', v('space-1')],
    ...pick('radius-').filter((k) => k !== 'radius-full').map((k) => [`--${k}`, v(k)] as [string, string]),
    ...pick('shadow-').map((k) => [`--${k}`, v(k)] as [string, string]),
    ['--blur-brand', v('blur')],
    ['--ease-out', v('ease-out')], ['--ease-in-out', v('ease-in-out')],
    ['--container-content', v('content')],
  ];
  const bps: [string, string][] = [['--breakpoint-*', 'initial'], ...Object.entries(BREAKPOINTS).map(([k, px]) => [`--breakpoint-${k}`, `${px}px`] as [string, string])];
  return HEAD('Tailwind v4 theme from the kit tokens. Import after "tailwindcss" and tokens.css.')
    + block('@theme', decls(bps)) + block('@theme inline', decls(theme));
}

// shadcn's variable names, mapped onto kit roles. shadcn's `accent` is a hover fill, not the primary colour: it maps to surface-2.
export const SHADCN: [shadcn: string, kit: string][] = [
  ['background', 'page'], ['foreground', 'text'],
  ['card', 'surface'], ['card-foreground', 'text'], ['popover', 'popover'], ['popover-foreground', 'text'],
  ['primary', 'accent'], ['primary-foreground', 'on-accent'],
  ['secondary', 'surface-2'], ['secondary-foreground', 'text'],
  ['muted', 'surface-2'], ['muted-foreground', 'muted'],
  ['accent', 'surface-2'], ['accent-foreground', 'text'],
  ['destructive', 'danger'], ['border', 'line'], ['input', 'line-strong'], ['ring', 'focus'], ['radius', 'radius-md'],
  ['sidebar', 'surface'], ['sidebar-foreground', 'text'], ['sidebar-primary', 'accent'], ['sidebar-primary-foreground', 'on-accent'],
  ['sidebar-accent', 'surface-2'], ['sidebar-accent-foreground', 'text'], ['sidebar-border', 'line'], ['sidebar-ring', 'focus'],
];

// A custom property that holds var() is resolved on the element that declares it, and children inherit the result. So the
// bridges are declared again on every element that changes the mode or the brand, or a nested theme would not reach them.
export function toShadcnCss(): string {
  return HEAD('shadcn/ui variables from the kit tokens: shadcn components take the kit look. Import after tokens.css; never together with from-shadcn.css.')
    + block(':where(:root, [data-theme], [data-brand])', decls(SHADCN.map(([s, k]) => [`--${s}`, `var(--k-${k})`])));
}

// The reverse, for kit pieces inside an existing shadcn app (its :root and .dark own the colours). Roles shadcn has no
// name for (success, warning, overlay, over) keep the kit values. Radius steps follow shadcn's --radius like its own sm/lg/xl.
export function fromShadcnCss(): string {
  const back: [string, string][] = ([
    ['page', 'background'], ['surface', 'card'], ['surface-2', 'muted'], ['popover', 'popover'], ['text', 'foreground'], ['muted', 'muted-foreground'],
    ['line', 'border'], ['line-strong', 'input'], ['accent', 'primary'], ['on-accent', 'primary-foreground'], ['focus', 'ring'], ['danger', 'destructive'],
  ] as const).map(([k, s]) => [`--k-${k}`, `var(--${s})`]);
  const radius: [string, string][] = [['--k-radius-sm', 'calc(var(--radius) - 4px)'], ['--k-radius-md', 'var(--radius)'], ['--k-radius-lg', 'calc(var(--radius) + 6px)'], ['--k-radius-xl', 'calc(var(--radius) + 14px)']];
  return HEAD('Kit tokens from a host\'s shadcn/ui theme: kit components take the shadcn look. Import after the shadcn theme and tokens.css; never together with to-shadcn.css.')
    + block(':where(:root)', decls([['color-scheme', 'light']]))
    + block(':where(.dark)', decls([['color-scheme', 'dark']]))
    + block(':where(:root, .dark, [data-theme], [data-brand])', decls([...back, ['--k-page-fill', 'var(--background)'], ...radius]));
}

// tokens.json: W3C design-tokens format, one group per set (scale, light, dark, brand/<name>, or brand/<name>/<mode> for a brand
// with both modes), for Figma or Tokens Studio.
export function tokensJson(): string {
  const typeOf = (name: string): string | undefined =>
    name.startsWith('font-') ? 'fontFamily' : name.startsWith('dur-') ? 'duration' : name.startsWith('z-') || name.startsWith('leading-') ? 'number'
      : /^(text-(?!display)|space-|radius-|content$|blur$)/.test(name) ? 'dimension' : undefined;
  const token = (name: string, value: string, type?: string) => ({ ...(type ? { $type: type } : {}), $value: value });
  const colors = (c: Partial<Colors>) => Object.fromEntries(Object.entries(c).map(([k, v]) => [k, token(k, v as string, k === 'page-fill' && !v!.startsWith('#') ? undefined : 'color')]));
  const scales = (s: Partial<Record<string, string>>) => Object.fromEntries(Object.entries(s).map(([k, v]) => [k, token(k, v!, typeOf(k))]));
  const out: Record<string, unknown> = {
    $description: 'Kit design tokens (CSS: --k-<name>). Generated by @kit/tokens from src/tokens.ts: do not edit.',
    scale: scales(SCALES), light: colors(MODES.light), dark: colors(MODES.dark),
  };
  for (const [name, b] of Object.entries(BRANDS)) {
    const sets = brandSets(b);
    for (const [mode, c] of sets) out[sets.length === 1 ? `brand/${name}` : `brand/${name}/${mode}`] = { ...colors(c), ...scales(b.scales ?? {}) };
  }
  return JSON.stringify(out, null, 2) + '\n';
}

// Every generated file, by its path inside the package.
export const OUTPUTS: Record<string, () => string> = {
  'css/tokens.css': tokensCss, 'css/tailwind.css': tailwindCss, 'css/to-shadcn.css': toShadcnCss, 'css/from-shadcn.css': fromShadcnCss, 'tokens.json': tokensJson,
};
