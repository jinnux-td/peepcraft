// Converts the Transhumans SVGs into src/figures/<Name>.ts plus an index. Usage: node scripts/build-figures.ts "<path to>/transhumans art/SVG"
// The files hold only <path d fill="black|white"> in a 1080 canvas, so a path is `{ d, paper }`; anything else stops the build rather than being dropped.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const pascal = (s: string) => s.replace(/[^A-Za-z0-9]+/g, ' ').trim().split(' ').map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const kebab = (s: string) => s.replace(/[^A-Za-z0-9]+/g, ' ').trim().toLowerCase().replace(/ /g, '-')

const root = process.argv[2]
if (!root) throw new Error('usage: node scripts/build-figures.ts "<transhumans art>/SVG"')
const out = new URL('../src/figures/', import.meta.url).pathname
rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true })

const names: string[] = []
for (const f of readdirSync(root).filter((f) => f.endsWith('.svg')).sort()) {
  const label = f.replace(/\.svg$/, '')
  const svg = readFileSync(join(root, f), 'utf8')
  const vb = /<svg[^>]*viewBox="0 0 (\d+) (\d+)"/.exec(svg)
  if (!vb) throw new Error(`${f}: no viewBox`)
  const tags = [...svg.matchAll(/<(\/?)([a-zA-Z]+)/g)].filter((m) => !m[1]).map((m) => m[2])
  const odd = tags.filter((t) => t !== 'svg' && t !== 'path')
  if (odd.length) throw new Error(`${f}: unexpected <${odd[0]}>`)
  const paths = [...svg.matchAll(/<path d="([^"]+)" fill="(black|white)"\s*\/>/g)].map((m) => ({ d: m[1], paper: m[2] === 'white' }))
  if (paths.length !== tags.length - 1) throw new Error(`${f}: ${tags.length - 1} paths but ${paths.length} converted (an attribute this converter does not know)`)
  const ident = pascal(label), id = kebab(label)
  if (names.includes(ident)) throw new Error(`${f}: name collides`)
  names.push(ident)
  const body = paths.map((p) => `  { d: ${JSON.stringify(p.d)}, paper: ${p.paper} },`).join('\n')
  writeFileSync(join(out, `${ident}.ts`), `// Generated by scripts/build-figures.ts from ${f}. Do not edit.
import { figure } from '../figure.ts'

export const ${ident} = figure({ id: ${JSON.stringify(id)}, label: ${JSON.stringify(label)}, width: ${vb[1]}, height: ${vb[2]} }, [
${body}
])
`)
}
writeFileSync(join(out, 'index.ts'), `// Generated by scripts/build-figures.ts. Do not edit.
${names.map((n) => `import { ${n} } from './${n}.ts'`).join('\n')}

export const figures = [
${names.map((n) => `  ${n},`).join('\n')}
] as const
`)
console.log('figures', names.length)
