// Measures the outline of every look PeepCraft frames on its own (each type, each type with an extra, each figure) in Chromium, as the
// creator's stage did with getBBox, and writes packages/peeps-engine/src/boxes.ts. Run it when atoms, figures or extras change:
//   npm run measure:peeps
import { writeFileSync } from 'node:fs'
import { chromium } from 'playwright-core'
import { loadAll } from '@kit/peeps'
import { figures } from '@kit/transhumans'
import { boxKey, boxKeys, exportSvg, fallbackBox, resolve, type PeepCraftDoc } from '@kit/peeps-engine'

await loadAll()
await Promise.all(figures.map((f) => f.load()))

const looks = boxKeys()
// Each look drawn with the type's default parts, as the stage first shows it; the group the stage measured is the one inside the transform.
const svgs = looks.map((l) => {
  const doc: PeepCraftDoc = { v: 1, type: l.type, ...(l.figure ? { figure: l.figure } : {}), ...(l.extra ? { extra: { id: l.extra.id } } : {}) }
  const s = resolve(doc)
  return `<div data-key="${boxKey(l)}">${exportSvg(s, fallbackBox(s))}</div>`
})

const browser = await chromium.launch()
try {
  const page = await browser.newPage()
  await page.setContent(`<!doctype html><body>${svgs.join('')}</body>`)
  const measured: Record<string, { x: number; y: number; width: number; height: number }> = await page.evaluate(() => Object.fromEntries(
    [...document.querySelectorAll<HTMLElement>('[data-key]')].map((el) => {
      const g = el.querySelector<SVGGElement>('svg > g[transform] > g')!
      const b = g.getBBox(), r = (n: number) => Math.round(n * 100) / 100
      return [el.dataset.key!, { x: r(b.x), y: r(b.y), width: r(b.width), height: r(b.height) }]
    })))
  const empty = Object.entries(measured).filter(([, b]) => !(b.width > 0 && b.height > 0)).map(([k]) => k)
  if (empty.length) throw new Error(`measured nothing for ${empty.join(', ')}`)
  const lines = Object.entries(measured).map(([k, b]) => `  ${JSON.stringify(k)}: { x: ${b.x}, y: ${b.y}, width: ${b.width}, height: ${b.height} },`)
  const out = new URL('../packages/peeps-engine/src/boxes.ts', import.meta.url)
  writeFileSync(out, `// Generated by scripts/measure-boxes.ts (npm run measure:peeps): the outline of each picture the creator frames, by boxKey, measured once in
// Chromium (getBBox) with the type's default parts. Do not edit; run the script again when atoms, figures or extras change.
import type { Box } from '@kit/peeps'

export const boxes: Readonly<Record<string, Box>> = {
${lines.join('\n')}
}
`)
  console.log(`${lines.length} outlines → packages/peeps-engine/src/boxes.ts`)
} finally {
  await browser.close()
}
